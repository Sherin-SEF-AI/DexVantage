"""Write docs/reference/cli.md, the batch command-line reference, from the real argument parser.

The parser is the one `dexvantage` builds (`dexvantage/app.py` main, with `batch.add_arguments` and every module it
calls), captured just before it parses: nothing here repeats an option by hand, so the reference cannot drift from the
code. Installed plugins are left out (`--no-plugins`), so their study flags do not appear in the published page.

    python scripts/gen_cli_reference.py            # write docs/reference/cli.md
    python scripts/gen_cli_reference.py --check    # exit 1 when the file on disk differs from what would be written

tests/test_docs_reference.py runs the check.
"""
from __future__ import annotations

import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'docs', 'reference', 'cli.md')
os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')


class _Captured(Exception):
    def __init__(self, parser):
        super().__init__('captured')
        self.parser = parser


def capture_parser() -> argparse.ArgumentParser:
    """The parser `dexvantage` builds, taken from `app.main` as it is about to parse (no window, nothing run)."""
    if ROOT not in sys.path:
        sys.path.insert(0, ROOT)
    from dexvantage import app

    real = argparse.ArgumentParser.parse_args

    def grab(self, *a, **k):
        if self.prog == 'dexvantage':
            raise _Captured(self)
        return real(self, *a, **k)

    argparse.ArgumentParser.parse_args = grab
    try:
        app.main(['--no-plugins'])
    except _Captured as c:
        return c.parser
    finally:
        argparse.ArgumentParser.parse_args = real
    raise RuntimeError('dexvantage built no parser')


def _usage(a: argparse.Action) -> str:
    if not a.option_strings:
        return f'`{a.metavar or a.dest}`'
    meta = ''
    if a.nargs != 0:
        if a.metavar is not None:
            meta = ' ' + (' '.join(a.metavar) if isinstance(a.metavar, tuple) else str(a.metavar))
        elif a.choices:
            meta = ' {' + ','.join(str(c) for c in a.choices) + '}'
        else:
            meta = ' ' + a.dest.upper()
        if a.nargs in ('+', '*'):
            meta += ' …'
    return ', '.join(f'`{o}{meta}`' for o in a.option_strings)


def _help(a: argparse.Action) -> str:
    text = (a.help or '').replace('%(default)s', str(a.default)).replace('%%', '%')
    text = ' '.join(text.split()).replace('|', '\\|')
    if a.choices and a.option_strings and '{' not in _usage(a):
        text += f' (one of: {", ".join(str(c) for c in a.choices)})'
    return text or '—'


def render(parser: argparse.ArgumentParser | None = None) -> str:
    ap = parser or capture_parser()
    from dexvantage import batch
    lines = [
        '# Command-line reference',
        '',
        '<!-- Generated by scripts/gen_cli_reference.py from the parser dexvantage builds; do not edit by hand. -->',
        '',
        f'`{ap.prog}`: {ap.description}. Every option below is the parser\'s own, in its groups and order; the '
        'worked examples are in the [user guide](../user-guide.md#batch). Installed plugins add their own study flags '
        '(`dexvantage --help` lists them; `--no-plugins` leaves them out).',
        '',
        '    dexvantage [PROJECT.dexv | --sample NAME] [OPTION …]',
        '',
        '## Exit codes',
        '',
        '| Code | Meaning |',
        '|---|---|',
        f'| {batch.EXIT_OK} | done (validation: every check passed; reproduce: the numbers reproduce; a scorecard: '
        'every requirement passes) |',
        f'| {batch.EXIT_FAIL} | a failed check, a requirement that does not pass, a result that does not reproduce, an '
        'incomplete gather, two projects that differ |',
        f'| {batch.EXIT_ERROR} | an error that stopped the run, said in one sentence on standard error (a file that '
        'cannot be read, a bad option, a study that cannot work with its inputs) |',
        '',
        '`-` as an output writes to standard output. A study flag given a folder (one that exists, or a path ending '
        'in `/`) writes `<folder>/<flag>.json`.',
        '',
    ]
    for g in ap._action_groups:
        acts = [a for a in g._group_actions if a.help is not argparse.SUPPRESS]
        if not acts:
            continue
        title = g.title or 'options'
        lines += [f'## {title[0].upper()}{title[1:]}', '']
        if g.description:
            lines += [' '.join(g.description.split()), '']
        lines += ['| Option | What it does |', '|---|---|']
        for a in acts:
            lines.append(f'| {_usage(a)} | {_help(a)} |')
        lines.append('')
    n = sum(1 for a in ap._actions if a.option_strings)
    lines += [f'{n} options in all.', '']
    return '\n'.join(lines)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description='Write docs/reference/cli.md from the dexvantage parser.')
    p.add_argument('--check', action='store_true', help='exit 1 when the file differs from what would be written')
    p.add_argument('--out', default=OUT, help='where to write (default docs/reference/cli.md)')
    args = p.parse_args(argv)
    text = render()
    if args.check:
        have = open(args.out, encoding='utf-8').read() if os.path.exists(args.out) else ''
        if have != text:
            print(f'{os.path.relpath(args.out, ROOT)} is out of date: run python scripts/gen_cli_reference.py')
            return 1
        print(f'{os.path.relpath(args.out, ROOT)} is up to date.')
        return 0
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'wrote {os.path.relpath(args.out, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
