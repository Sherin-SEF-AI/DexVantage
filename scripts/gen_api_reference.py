"""Write docs/reference/api.md, the Python API reference, from the docstrings of the code itself.

What is listed: every name in `dexvantage.api.__all__` (the names `import dexvantage as dv` gives), with the methods and
properties of its classes and of the namespace objects (`dv.datasets`, `dv.stats`, `dv.campaign`, …), then the plugin
SDK (`dexvantage.plugin_sdk`: `PluginAPI` and the module functions a plugin author uses). Signatures come from
`inspect.signature`, text from `inspect.getdoc`; nothing is written by hand, so the page cannot drift from the code.
No Qt is imported (the API path imports none).

    python scripts/gen_api_reference.py            # write docs/reference/api.md
    python scripts/gen_api_reference.py --check    # exit 1 when the file on disk differs from what would be written

tests/test_docs_reference.py runs the check.
"""
from __future__ import annotations

import argparse
import inspect
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
OUT = os.path.join(ROOT, 'docs', 'reference', 'api.md')
NO_DOC = 'No docstring.'
PLUGIN_FUNCS = ('discover', 'load', 'loaded', 'enabled', 'unload', 'report_lines')


def _ann(a) -> str:
    """An annotation as written in the source (the modules use postponed annotations, so most are strings)."""
    if isinstance(a, str):
        return a.strip('\'"')
    return getattr(a, '__name__', None) or str(a).replace('typing.', '')


def _sig(obj, name: str) -> str:
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return f'{name}(…)'
    parts, star_done = [], False
    params = list(sig.parameters.values())
    for i, p in enumerate(params):
        if p.kind == p.KEYWORD_ONLY and not star_done and not any(q.kind == q.VAR_POSITIONAL for q in params[:i]):
            parts.append('*')
        star_done = star_done or p.kind in (p.KEYWORD_ONLY, p.VAR_POSITIONAL)
        prefix = '*' if p.kind == p.VAR_POSITIONAL else '**' if p.kind == p.VAR_KEYWORD else ''
        s = prefix + p.name
        if p.annotation is not p.empty:
            s += f': {_ann(p.annotation)}'
        if p.default is not p.empty:
            s += (' = ' if p.annotation is not p.empty else '=') + repr(p.default)
        parts.append(s)
    out = f'{name}({", ".join(parts)})'
    if sig.return_annotation is not sig.empty:
        out += f' -> {_ann(sig.return_annotation)}'
    return re.sub(r' at 0x[0-9a-f]+', '', out)       # a default that is an object: no memory address in the docs


def _doc(obj) -> str:
    d = inspect.getdoc(obj)
    if not d:
        return NO_DOC
    d = d.replace('\r\n', '\n').strip()
    if '>>>' in d:                                  # doctests read as code
        out, block = [], False
        for line in d.split('\n'):
            starts = line.lstrip().startswith('>>>')
            if starts and not block:
                out.append('```pycon')
                block = True
            elif block and not line.strip():
                out.append('```')
                block = False
            out.append(line)
        if block:
            out.append('```')
        d = '\n'.join(out)
    return d


def _members(cls) -> list:
    """Public methods and properties defined on the class or its DexVantage bases (not dict's or list's own)."""
    out = []
    seen = set()
    for klass in cls.__mro__:
        if not (klass.__module__ or '').startswith('dexvantage'):
            continue
        for name, val in vars(klass).items():
            if name.startswith('_') or name in seen:
                continue
            seen.add(name)
            if isinstance(val, property):
                out.append((name, 'property', val))
            elif isinstance(val, (staticmethod, classmethod)):
                out.append((name, 'method', val.__func__))
            elif inspect.isfunction(val):
                out.append((name, 'method', val))
    return sorted(out, key=lambda t: t[0])


def _entry(lines: list, title: str, obj, level: int = 3):
    lines += [f'{"#" * level} `{title}`', '', _doc(obj), '']


def _class(lines: list, prefix: str, name: str, cls, level: int = 3):
    _entry(lines, _sig(cls, f'{prefix}{name}') if prefix != 'namespace' else name, cls, level)
    for mname, kind, val in _members(cls):
        shown = f'{name}.{mname}' if kind == 'property' else _sig(val, f'{name}.{mname}').replace('(self, ', '(') \
            .replace('(self)', '()').replace('(cls, ', '(').replace('(cls)', '()')
        _entry(lines, shown, val, level + 1)


def render() -> str:
    if ROOT not in sys.path:
        sys.path.insert(0, ROOT)
    from dexvantage import api, plugin_sdk
    lines = [
        '# Python API reference',
        '',
        '<!-- Generated by scripts/gen_api_reference.py from the docstrings; do not edit by hand. -->',
        '',
        '`import dexvantage as dv` gives every name below without importing Qt. The worked examples are in the '
        '[user guide](../user-guide.md#python-api) and [guide/api.md](../guide/api.md); this page is the docstrings '
        'of `dexvantage/api.py`, `dexvantage/api_research.py`, `dexvantage/api_cluster.py` and '
        '`dexvantage/plugin_sdk.py`, in the order `dv` lists them.',
        '',
        '## The module',
        '',
        _doc(api),
        '',
    ]
    funcs, classes, spaces = [], [], []
    for name in api.__all__:
        obj = getattr(api, name)
        if inspect.isclass(obj):
            classes.append((name, obj))
        elif inspect.isfunction(obj):
            funcs.append((name, obj))
        else:
            spaces.append((name, obj))
    lines += ['## Functions', '']
    for name, fn in funcs:
        _entry(lines, _sig(fn, f'dv.{name}'), fn)
    lines += ['## Classes', '']
    for name, cls in classes:
        _class(lines, 'dv.', name, cls)
    lines += ['## Namespaces', '', 'Objects whose methods group one area: call them as `dv.<name>.<method>(…)`.', '']
    for name, obj in spaces:
        cls = type(obj)
        lines += [f'### `dv.{name}`', '', _doc(cls) if cls.__doc__ else _doc(obj), '']
        for mname, kind, val in _members(cls):
            shown = f'dv.{name}.{mname}' if kind == 'property' else \
                _sig(val, f'dv.{name}.{mname}').replace('(self, ', '(').replace('(self)', '()')
            _entry(lines, shown, val, 4)
    lines += ['## The plugin SDK (`dexvantage.plugin_sdk`)', '', _doc(plugin_sdk), '']
    _class(lines, 'plugin_sdk.', 'PluginAPI', plugin_sdk.PluginAPI)
    _entry(lines, _sig(plugin_sdk.PluginError, 'plugin_sdk.PluginError'), plugin_sdk.PluginError)
    for fname in PLUGIN_FUNCS:
        fn = getattr(plugin_sdk, fname)
        _entry(lines, _sig(fn, f'plugin_sdk.{fname}'), fn)
    text = '\n'.join(lines).rstrip() + '\n'
    return re.sub(r'\n{3,}', '\n\n', text)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description='Write docs/reference/api.md from the API docstrings.')
    p.add_argument('--check', action='store_true', help='exit 1 when the file differs from what would be written')
    p.add_argument('--out', default=OUT, help='where to write (default docs/reference/api.md)')
    args = p.parse_args(argv)
    text = render()
    if args.check:
        have = open(args.out, encoding='utf-8').read() if os.path.exists(args.out) else ''
        if have != text:
            print(f'{os.path.relpath(args.out, ROOT)} is out of date: run python scripts/gen_api_reference.py')
            return 1
        print(f'{os.path.relpath(args.out, ROOT)} is up to date.')
        return 0
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'wrote {os.path.relpath(args.out, ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
