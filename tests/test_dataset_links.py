def test_joint_names_are_matched_by_name_normalised_name_and_order():
    p, r, m = _ur5e()
    n = 4
    t = np.arange(n) / 10.0
    q = np.arange(n * m.nq, dtype=float).reshape(n, m.nq) * 1e-3
    ep = Episode('e', 0, t, q[:, ::-1], list(m.joint_names)[::-1])            # columns in another order
    jm = JT.on_model(ep, m)
    assert jm.how == 'names' and jm.found == m.nq and np.allclose(jm.Q, q) and not jm.notes
    lerobot = [n_.replace('_joint', '') + '.pos' for n_ in m.joint_names]      # LeRobot's naming
    jm = JT.on_model(Episode('e', 0, t, np.degrees(q), lerobot), m, unit='deg')
    assert jm.how == 'normalised names' and np.allclose(jm.Q, q) and 'degrees' in ' '.join(jm.notes)
    part = Episode('e', 0, t, np.c_[q[:, :6], np.ones(n)], ['main_' + x for x in lerobot[:6]] + ['extra'])
    jm = JT.on_model(part, m)
    assert jm.found == 6 and np.allclose(jm.Q[:, :6], q[:, :6]) and np.allclose(jm.Q[:, 6:], m.home[6:])
    text = ' '.join(jm.notes)
    assert '8 joint(s)' in text and 'held at home' in text and 'extra' in text
    jm = JT.on_model(Episode('e', 0, t, q, [f'state_{i}' for i in range(m.nq)]), m)
    assert jm.how == 'order' and np.allclose(jm.Q, q) and 'order' in jm.notes[0]
    big = Episode('e', 0, t, np.full((n, m.nq), 90.0), list(m.joint_names))
    assert any('look like degrees' in x for x in JT.on_model(big, m).notes)
    with pytest.raises(DatasetError, match='None of the dataset') as e:
        JT.on_model(Episode('e', 0, t, np.zeros((n, 3)), ['a', 'b', 'c']), m)
    assert 'choose the robot' in str(e.value)


def test_interpolation_against_the_closed_form():
    t = np.array([0.0, 0.1, 0.2, 0.4])
    Q = np.c_[3.0 * t + 1.0, -2.0 * t]
    x = np.array([-0.01, 0.0, 0.05, 0.13, 0.3, 0.4, 0.4 + 1e-7, 0.41])
    out = JT.interpolate(t, Q, x)
    inside = (x >= 0) & (x <= 0.4 + 1e-6)
    assert np.isnan(out[~inside]).all()
    xi = np.clip(x[inside], 0, 0.4)
    assert np.allclose(out[inside], np.c_[3.0 * xi + 1.0, -2.0 * xi], atol=1e-12)
    Qn = Q.copy()
    Qn[2, 0] = np.nan                                       # a joint not yet recorded at row 2
    o2 = JT.interpolate(t, Qn, [0.05, 0.15, 0.2, 0.3])
    assert np.isfinite(o2[0]).all() and np.isnan(o2[1, 0]) and np.isnan(o2[2, 0]) and np.isnan(o2[3, 0])
    assert np.isfinite(o2[:, 1]).all()


