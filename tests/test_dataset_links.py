@pytest.mark.mujoco_render
def test_grasps_from_synthetic_episodes(tmp_path):
    """Episodes generated by core/sim/episodes.py playing the UR5e sample's pick (rendered, faults off)."""
    from dexvantage.core.sim import episodes as SE
    p, r, m = _ur5e()
    s = SE.generate(p, str(tmp_path / 'synth'), {'episodes': 2, 'size': [64, 48], 'faults': [], 'q_offset_rad': 0.0,
                                                  'motion': 'trajectories', 'noise_dn': 0.0, 'seed': 3})
