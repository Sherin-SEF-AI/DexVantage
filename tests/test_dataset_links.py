"""Data links (Phase 8, spec §7.3 'taken from a recorded dataset', §8.1 'a LeRobot episode', 'ROS 2 topics'):
grasp sets found where the gripper closes in a dataset's episodes (core/grasps.from_dataset), hand-eye sessions
captured from a dataset's frames with the board in view (core/calib/capture.capture_dataset), the joint matching and
interpolation they share (core/datasets/joints.py), the Tasks and Hand-eye solve pages' commands, and the plain errors.

The datasets are synthetic and their truth is known by construction: LeRobot datasets written from the UR5e sample's
scripted pick and from board images rendered at planned poses through a camera moved by a known offset (as
core/calib/simcapture does), a ROS 2 MCAP bag of the same capture with its own clocks, and episodes generated by
core/sim/episodes.py (the generator has no board in its scene, so the hand-eye datasets are written here). The
captures and grasp sets are computed from the data alone and only then compared with the construction."""
