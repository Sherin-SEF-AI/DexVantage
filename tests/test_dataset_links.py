@pytest.mark.parametrize('version', ['v2.1', 'v3.0'])
def test_grasps_from_a_lerobot_dataset_are_where_the_gripper_closes(pick_dataset, version):
    p, r, m = _ur5e()
    gs = GR.from_dataset(p, pick_dataset[version], r.uid)
    assert gs['source'] == 'dataset' and gs['robot_uid'] == r.uid and [g['id'] for g in gs['poses']] == ['e0c1',
                                                                                                         'e1c1']
    st = gs['settings']
    assert st['format'] == 'lerobot' and st['version'] == version and st['dataset'] == f'pick_{version}'
    assert st['joint_match'] == ['names'] and st['mode'] == 'closures' and set(st['defaults']) == {'close_mm',
                                                                                                    'approach_mm'}
    # the script closes the fingers from 1.5 s to 2.0 s (episode 1, 1.5 times slower: 2.25 s to 3.0 s); the stroke
    # starts at the last row before the fingers move and ends at the first row after they stop (rows 1/30 s apart)
    from dexvantage.core.frames import Pose
    from dexvantage.core.robot import trajectory as TR
    tr = p.tasks.trajectories[0]
    ev = st['events']
    assert [e['episode'] for e in ev] == [0, 1]
    for g, e, (a, b), scale in zip(gs['poses'], ev, ((1.5, 2.0), (2.25, 3.0)), (1.0, 1.5)):
        onset, end = np.floor(a * FPS + 1e-9) / FPS, np.ceil(b * FPS - 1e-9) / FPS
        assert abs(e['t'] - onset) < 1e-5 and abs(e['t_end'] - end) < 1e-5 and abs(g['t'] - onset) < 1e-5
        assert abs(e['drop_m'] - 0.0741) < 5e-4
        # the gripper frame at the onset is the script's at that time (float32 state columns: < 1e-6 m)
        T = m.link_pose(m.clip(TR.on_model(tr, m.joint_names, m.home, onset / scale)), gs['frame'])
        P = Pose.from_dict(g['pose']).matrix()
        assert np.allclose(P[:3, 3], T[:3, 3], atol=1e-6) and np.allclose(P[:3, :3], T[:3, :3], atol=1e-6)
    doc = json.dumps(gs)
    assert pick_dataset[version] not in doc and os.sep + 'tmp' not in doc     # the name only, never the path
    one = GR.from_dataset(p, pick_dataset[version], r.uid, episodes=[1])
    assert [g['id'] for g in one['poses']] == ['e1c1']
    every = GR.from_dataset(p, pick_dataset[version], r.uid, mode='every', every=30, episodes=[0])
    assert len(every['poses']) == 5 and every['name'].endswith('(every 30)') and every['poses'][1]['t'] == 1.0


