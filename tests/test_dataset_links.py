FPS = 30
CAM_KEY = 'observation.images.wrist_d405'
HE_FPS, DWELL_S, MOVE_S = 5, 1.0, 0.8           # the hand-eye recording: hold each pose 1 s, move 0.8 s
TOL_MM, TOL_DEG = 0.2, 0.05                     # the solve against the true mount (see test_handeye_from_lerobot)


# ====================================================================== helpers
def _ur5e():
    p = sample_project('ur5e')
    r = p.robots[0]
    return p, r, get_model(p, r.uid)


def _pick_episode(p, m, index, scale=1.0, names=None, deg=False):
    """The UR5e sample's scripted pick (it closes the 2F-85 once, from t = 1.5 s to 2.0 s) at FPS rows, its time
    stretched by scale."""
    from dexvantage.core.robot import trajectory as TR
    tr = p.tasks.trajectories[0]
    t = np.arange(0.0, 4.5 * scale + 1e-9, 1.0 / FPS)
    Q = np.array([TR.on_model(tr, m.joint_names, m.home, x / scale) for x in t])
    if deg:
        Q = np.degrees(Q)
    return Episode(f'e{index}', index, t, Q, list(names or m.joint_names), fps=float(FPS), robot_type='ur5e')


class MemDataset(Dataset):
    """A dataset held in memory (episodes given), for the cases a file format does not need to be in."""
    format, version, path = 'memory', '', 'memory'

    def __init__(self, eps):
        self.eps = eps

    def episodes(self):
        return [EpisodeRef(e.index, e.id, len(e.t)) for e in self.eps]

    def load(self, i):
        return next(e for e in self.eps if e.index == i)


def _stream(key, frames, ts, fps):
    def dec(idx):
        for i in (range(len(frames)) if idx is None else idx):
            yield i, frames[i]
    h, w = frames[0].shape[:2]
    return CameraStream(key, w, h, float(fps), np.asarray(ts, float), _decode=dec)


